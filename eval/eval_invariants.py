"""Step 1 viability check for the invariant line, on synthetic tables.

Reports four numbers:
  1. how many invariants were found;
  2. how many candidates the all-columns filter rejected;
  3. which of the found ones are genuine (classified by hand, listed in full);
  4. how many test queries an invariant can reach — two separate figures.

WHY COVERAGE IS TWO NUMBERS. A class-A invariant constrains a single cell.

  * broad — the query mentions a row that takes part in some invariant. Easy
    to count, but it does not mean the answer can be refuted.
  * narrow — the answer IS that cell's value, so the invariant constrains it
    directly. Smaller and more honest.

A query such as "total revenue for 2023" aggregates four cells; checking it
would require knowing which cells the generated code summed, which is beyond
this step.

CIRCULARITY WARNING. These tables are generated by this project, and their
subtotal rows are computed as real sums of their sections. The detector will
find what was built in. This step therefore validates the MECHANISM, not the
idea. The real test is a genuine document, where nobody planted anything.

Run:  python -m eval.eval_invariants
"""
import json
import os
import re
import time

import pandas as pd

from core import invariants
from core import lang
from core.text_utils import tokenize
from load_data import load_tables, resolve_pdf

HERE = os.path.dirname(os.path.abspath(__file__))
PDF = "sample_report_multipage.pdf"

# Queries whose answer is one cell. For every other type the answer is derived
# from several cells, so a class-A invariant cannot bound it directly.
SINGLE_CELL_TYPES = {"SCALAR_LOOKUP"}


def load_queries() -> list:
    out, seen = [], set()
    prof = lang.get()
    for name in (prof.TEST_SET_FULL, prof.TEST_SET_PHASE1):
        with open(os.path.join(HERE, name), encoding="utf-8") as f:
            for it in json.load(f):
                if it["query"] in seen:
                    continue
                seen.add(it["query"])
                out.append({"query": it["query"], "type": it["type"], "set": name})
    return out


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", str(s)).strip().lower()


MIN_PREFIX = 4


def _token_matches(label_token: str, query_tokens: set) -> bool:
    """Token match tolerant of the stemmer's asymmetry.

    The suffix stripper is not a real morphological analyser: "витрати" loses
    "ти" and becomes "витра", while "витрат" keeps its form. The same root then
    yields different stems and an exact set comparison misses the pair. Two
    tokens count as the same root when one is a prefix of the other and the
    shared part is long enough to be meaningful.
    """
    if label_token in query_tokens:
        return True
    for qt in query_tokens:
        short, long_ = ((label_token, qt) if len(label_token) <= len(qt)
                        else (qt, label_token))
        if len(short) >= MIN_PREFIX and long_.startswith(short):
            return True
    return False


def referenced_rows(query: str, tables: dict, mode: str = "stem") -> list:
    """Row labels mentioned in the query text.

    A heuristic mapping, not a parse: what follows measures this mapping, not
    ground truth about what a query means.

    `mode="substring"` is the naive version and undercounts badly, because
    Ukrainian inflects: the query says "сума фінансових витрат" while the label
    reads "Фінансові витрати". `mode="stem"` reuses the project's stemmer and
    matches when every content token of the label appears in the query.
    """
    if mode == "substring":
        q = _norm(query)
        return [(name, str(label))
                for name, df in tables.items() if df.shape[1]
                for label in df.iloc[:, 0].tolist()
                if len(_norm(label)) >= 5 and _norm(label) in q]

    q_tokens = tokenize(query)
    hits = []
    for name, df in tables.items():
        if df.shape[1] == 0:
            continue
        for label in df.iloc[:, 0].tolist():
            lab_tokens = tokenize(label)
            if not lab_tokens:
                continue
            if mode == "stem":
                ok = lab_tokens <= q_tokens
            else:  # prefix
                ok = all(_token_matches(lt, q_tokens) for lt in lab_tokens)
            if ok:
                hits.append((name, str(label)))
    return hits


def main():
    tables = load_tables(PDF)

    print("=" * 78)
    print("КРОК 1 — ДЕТЕКТОР АРИФМЕТИЧНИХ ІНВАРІАНТІВ НА СИНТЕТИЦІ")
    print("=" * 78)
    print(f"Мова: {lang.active_lang()}   документ: {resolve_pdf(PDF)}")
    print(f"Таблиці: { {k: v.shape for k, v in tables.items()} }")
    print(f"Допуск: abs={invariants.ABS_TOL}, rel={invariants.REL_TOL:.1%}")
    print()

    t0 = time.perf_counter()
    result = invariants.detect(tables)
    elapsed = time.perf_counter() - t0

    inv = result["invariants"]

    print("--- 1. Скільки знайдено ---")
    per = pd.DataFrame([
        {"таблиця": name, "розмір": f"{d['shape'][0]}x{d['shape'][1]}",
         "суми рядків": d["n_row_sums"], "суми стовпців": d["n_col_sums"],
         "усього": d["n_invariants"], "перевірено кандидатів": d["candidates_tested"],
         "відсіяно": d["rejected"]}
        for name, d in result["per_table"].items()
    ])
    print(per.to_string(index=False))
    print()
    print(f"  ЗНАЙДЕНО ІНВАРІАНТІВ: {len(inv)}")
    print(f"  перевірено кандидатів: {result['candidates_tested']}")
    print(f"  ВІДСІЯНО фільтром «усі стовпці»: {result['rejected']} "
          f"({result['rejected'] / max(result['candidates_tested'], 1):.4%} пройшло)")
    print(f"  час пошуку: {elapsed:.2f} с")

    ind = invariants.independent_count(inv)
    tot_ind = sum(d["independent"] for d in ind.values())
    tot_der = sum(d["derived"] for d in ind.values())
    print(f"  з них НЕЗАЛЕЖНИХ: {tot_ind}, похідних (виводяться з інших): {tot_der}")
    for t, d in ind.items():
        print(f"    {t:10s} усього={d['total']}, незалежних={d['independent']}, "
              f"похідних={d['derived']}")

    print()
    print("--- 1b. Розгортка за допуском ---")
    print("  Фільтр «усі стовпці» сам по собі недостатній: рядки звіту значною")
    print("  мірою пропорційні одне одному, тож довільна комбінація з відповідними")
    print("  коефіцієнтами тримається в широкій смузі в УСІХ стовпцях одразу.")
    saved_rel, saved_abs = invariants.REL_TOL, invariants.ABS_TOL
    sweep = []
    for rel in (5e-3, 1e-3, 1e-4, 1e-6):
        invariants.REL_TOL = rel
        r = invariants.detect(tables)
        exact = [x for x in r["invariants"] if x["max_rel_error"] == 0.0]
        sweep.append({"допуск rel": f"{rel:.0e}", "знайдено": len(r["invariants"]),
                      "точних (err=0)": len(exact),
                      "коїнциденцій": len(r["invariants"]) - len(exact)})
    invariants.REL_TOL, invariants.ABS_TOL = saved_rel, saved_abs
    print(pd.DataFrame(sweep).to_string(index=False))
    print(f"  Робочий допуск: rel={saved_rel:.0e}")

    print()
    print("--- 2. Повний список знайденого (для ручної класифікації) ---")
    if not inv:
        print("  порожньо")
    for i, x in enumerate(sorted(inv, key=lambda v: (v["table"], v["n_members"])), start=1):
        print(f"  {i:2d}. {invariants.describe(x)}")
        print(f"      форма={x['form']}, членів={x['n_members']}, "
              f"стовпців={x['n_columns']}, макс.похибка={x['max_rel_error']:.2e}")

    print()
    print("--- 3. Покриття тестових запитів ---")
    queries = load_queries()
    constrained = invariants.rows_under_constraint(inv)

    rows = []
    for q in queries:
        hit = {}
        for m in ("substring", "stem", "prefix"):
            r = referenced_rows(q["query"], tables, mode=m)
            hit[m] = [(t, lbl) for t, lbl in r if lbl in constrained.get(t, set())]

        touched = hit["prefix"]
        broad = bool(touched)
        narrow = broad and q["type"] in SINGLE_CELL_TYPES
        rows.append({
            "type": q["type"], "query": q["query"],
            "touched": len(touched),
            "broad": broad,
            "broad_substring": bool(hit["substring"]),
            "broad_stem": bool(hit["stem"]),
            "narrow": narrow,
            "labels": "; ".join(lbl for _, lbl in touched[:2]),
        })

    df = pd.DataFrame(rows)
    n = len(df)
    n_broad = int(df.broad.sum())
    n_narrow = int(df.narrow.sum())

    print(f"  Унікальних запитів: {n}")
    print()
    print("  Широке покриття залежить від того, як зіставляти запит із міткою.")
    print("  Три варіанти матчера — щоб було видно чутливість числа:")
    for key, label in (("broad_substring", "підрядок (не бачить відмінків)"),
                       ("broad_stem", "стем, точний збіг множин"),
                       ("broad", "стем + префікс (робочий)")):
        k = int(df[key].sum())
        print(f"    {label:34s} {k}/{n} = {k / n:.0%}")
    print()
    print(f"  ШИРОКЕ покриття (запит згадує рядок під інваріантом): "
          f"{n_broad}/{n} = {n_broad / n:.0%}")
    print(f"  ВУЗЬКЕ покриття (відповідь = клітинка, яку інваріант обмежує): "
          f"{n_narrow}/{n} = {n_narrow / n:.0%}")

    print()
    print("  Розподіл широкого покриття за типом запиту:")
    by_type = df.groupby("type").agg(усього=("broad", "size"),
                                     широке=("broad", "sum"),
                                     вузьке=("narrow", "sum"))
    print(by_type.to_string())

    print()
    print("  Запити БЕЗ покриття:")
    miss = df[~df.broad]
    if miss.empty:
        print("    немає")
    for _, r in miss.iterrows():
        print(f"    [{r['type']}] {r['query']}")

    code = lang.active_lang()
    out = os.path.join(HERE, f"invariants_step1_coverage_{code}.csv")
    df.to_csv(out, index=False)
    inv_out = os.path.join(HERE, f"invariants_step1_found_{code}.json")
    with open(inv_out, "w", encoding="utf-8") as f:
        json.dump({"per_table": result["per_table"],
                   "candidates_tested": result["candidates_tested"],
                   "rejected": result["rejected"],
                   "independence": ind,
                   "tolerance": {"abs": invariants.ABS_TOL, "rel": invariants.REL_TOL},
                   "invariants": inv}, f, ensure_ascii=False, indent=1)

    print()
    print("Збережено:", out)
    print("Збережено:", inv_out)
    print()
    print("НАГАДУВАННЯ: синтетичні таблиці згенеровані цим проєктом, і підсумкові")
    print("рядки в них рахуються як справжні суми секцій. Крок 1 перевіряє")
    print("МЕХАНІКУ детектора, а не життєздатність ідеї — це робить Крок 2.")
    return result, df


if __name__ == "__main__":
    pd.set_option("display.width", 200)
    pd.set_option("display.max_colwidth", 60)
    main()
